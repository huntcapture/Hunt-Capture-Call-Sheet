export const generateTemplateCsv = (tab: SheetTemplateTab): string => {
  const escapeCsv = (val: string) => {
    if (val.includes(',') || val.includes('"') || val.includes('\n')) {
      return `"${val.replace(/"/g, '""')}"`;
    }
    return val;
  };

  const headerLine = tab.columns.map(escapeCsv).join(',');
  const rowLines = tab.sampleRows.map((row) => row.map(escapeCsv).join(','));
  return [headerLine, ...rowLines].join('\n');
};
